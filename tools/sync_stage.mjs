// Copy StiraCore's Stage into this app and apply the KiroCrew patches.
//
//   node tools/sync_stage.mjs [path-to-StiraCore]
//
// Source: StiraCore dashboard/stage (+ static/js/chat_core.js, static/i18n, static/ui/tokens.css).
// Every patch is a literal (or regex) replacement that must match: a missing match stops the
// sync, so an upstream change can never be patched half-way without anyone noticing.
// Files this app owns (kc_*.js, stira-shell.css) are never written here.

