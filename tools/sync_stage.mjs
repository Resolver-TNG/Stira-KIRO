// --- copy -------------------------------------------------------------------------------------
const OWN = new Set(['kc_core.js', 'kc_live.js', 'kc_confirm.js', 'kc_widget.js', 'kc_hotspots.js', 'kc_shelf.js', 'kc_desk.js', 'kc_forest.js', 'kc_watch.js']);
mkdirSync(join(out, 'js'), { recursive: true });
for (const name of readdirSync(join(out, 'js'))) {
  if (!OWN.has(name)) rmSync(join(out, 'js', name), { force: true });
}
for (const name of readdirSync(join(dash, 'stage', 'js'))) {
  if (name.endsWith('.js')) cpSync(join(dash, 'stage', 'js', name), join(out, 'js', name));
}
cpSync(join(dash, 'static', 'js', 'chat_core.js'), join(out, 'js', 'chat_core.js'));
rmSync(join(out, 'assets'), { recursive: true, force: true });
cpSync(join(dash, 'stage', 'assets'), join(out, 'assets'), {
  recursive: true,
  filter: (p) => !p.split(/[\\/]/).includes('source'), // build inputs, not served
});
rmSync(join(out, 'vendor'), { recursive: true, force: true });
cpSync(join(dash, 'stage', 'vendor'), join(out, 'vendor'), { recursive: true });

// --- patch helpers ----------------------------------------------------------------------------
function patchFile(rel, edits) {
  const file = join(out, rel);
  let text = readFileSync(file, 'utf8').replace(/\r\n/g, '\n'); // a Windows checkout has CRLF
  for (const [from, to, opts = {}] of edits) {
    const before = text;
    if (from instanceof RegExp) text = text.replace(from, to);
    else if (opts.all) text = text.split(from).join(to);
    else text = text.replace(from, to);
    if (text === before) throw new Error(`${rel}: patch did not match: ${String(from).slice(0, 80)}`);
  }
  writeFileSync(file, text);
}

// --- CSS: scope every global rule to the Stage root -------------------------------------------
const ROOT = '.stira-stage-root';
{
  let css = readFileSync(join(dash, 'stage', 'stage.css'), 'utf8').replace(/\r\n/g, '\n');
  const edits = [
    [':root {', `${ROOT} {`],
    ['* { box-sizing: border-box; }', `${ROOT}, ${ROOT} * { box-sizing: border-box; }`],
    ['html, body { margin: 0; height: 100%; background: var(--deep); color: var(--ink); }', `${ROOT} { margin: 0; height: 100%; background: var(--deep); color: var(--ink); }`],
    ['body { overflow: hidden; }', `${ROOT} { overflow: hidden; }`],
    ['body.stage-page { overflow: hidden; }\n', ''],
    [/\.stage-page \.app-shell \{[^}]*\}\n/, ''],
    [/\.stage-page \.app-main \{[^}]*\}\n/, ''],
    [/\bbody\./g, `${ROOT}.`],
    [/#app\b/g, '#stira-app'],
  ];
  for (const [from, to] of edits) {
    const before = css;
    css = typeof from === 'string' ? css.replace(from, to) : css.replace(from, to);
    if (css === before) throw new Error(`stage.css: patch did not match: ${String(from).slice(0, 80)}`);
  }
  let tokens = readFileSync(join(dash, 'static', 'ui', 'tokens.css'), 'utf8');
  const tBefore = tokens;
  tokens = tokens.split(':root').join(ROOT);
  if (tokens === tBefore) throw new Error('tokens.css: no :root');
  writeFileSync(join(out, 'stage.css'), `/* generated by tools/sync_stage.mjs from StiraCore: tokens.css + stage.css, scoped to ${ROOT} */\n${tokens}\n${css}`);
}

// --- i18n: only the keys the Stage reads ------------------------------------------------------
